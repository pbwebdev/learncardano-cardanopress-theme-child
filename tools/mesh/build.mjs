/*
  Bundles @meshsdk/core into one self-hosted ES module for the delegate page:
  assets/vendor/mesh/mesh.js. It is named .js, not .mjs, because SiteGround
  serves .mjs with no JavaScript MIME type and browsers refuse such modules.

    cd tools/mesh && npm ci && npm run build

  Mesh 1.9 inlines its WebAssembly, so the bundle is a single file. If a later
  version emits separate .wasm files, they are fetched from MESH_PUBLIC_PATH
  (default: the live theme's folder). Commit the regenerated
  assets/vendor/mesh/ — the deploy workflow just rsyncs the repo, it has no
  build step.
*/
import * as esbuild from "esbuild";
import { polyfillNode } from "esbuild-plugin-polyfill-node";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../../assets/vendor/mesh");
const publicPath =
  process.env.MESH_PUBLIC_PATH ||
  "/wp-content/themes/learncardano-cardanopress-theme-child/assets/vendor/mesh/";

if (existsSync(outDir)) rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const result = await esbuild.build({
  entryPoints: [resolve(here, "entry.js")],
  bundle: true,
  format: "esm",
  target: "es2022",
  platform: "browser",
  outfile: `${outDir}/mesh.js`,
  loader: { ".wasm": "file" },
  assetNames: "[name]-[hash]",
  publicPath,
  minify: true,
  legalComments: "none",
  sourcemap: false,
  define: {
    "process.env.NODE_ENV": '"production"',
    global: "globalThis",
  },
  banner: { js: "// Mesh SDK browser bundle (@meshsdk/core) for learncardano.io /delegate/ — generated by tools/mesh/build.mjs" },
  plugins: [
    polyfillNode({
      polyfills: { crypto: true, stream: true, events: true, buffer: true, util: true, process: true },
      globals: { buffer: true, process: true },
    }),
  ],
  metafile: true,
  logLevel: "info",
});

// Content hash for cache-busting (?ver=), read by lc_mesh_bundle_url(). Deploys
// reset file mtimes, so an mtime version would change on every deploy.
const hash = createHash("sha256").update(readFileSync(`${outDir}/mesh.js`)).digest("hex").slice(0, 12);
writeFileSync(`${outDir}/mesh.version`, hash);

console.log("\nMesh bundle written for", publicPath, "— version", hash);
for (const [file, info] of Object.entries(result.metafile.outputs)) {
  console.log(`  ${file}  ${(info.bytes / 1024 / 1024).toFixed(2)} MB`);
}
